#!/usr/bin/env python3
"""Generate repo manifests from projects.json.

The JSON file is the single source of truth. It keeps the GitHub-facing
inventory readable while the generated XML stays compatible with `repo`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PROJECTS = ROOT / "projects.json"
DEFAULT_MANIFEST = ROOT / "default.xml"
ECOSYSTEM_MANIFEST = ROOT / "ecosystem.xml"


def remote_name(host: str, owner: str) -> str:
    raw = f"{host}-{owner}".lower()
    return re.sub(r"[^a-z0-9_.-]+", "-", raw).strip("-")


def remote_fetch(host: str, owner: str) -> str:
    if host == "codeberg":
        return f"https://codeberg.org/{owner}"
    if host == "gitlab":
        return f"https://gitlab.com/{owner}"
    if host == "github":
        return f"https://github.com/{owner}"
    raise ValueError(f"unsupported host: {host}")


def load_projects(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    projects = data.get("projects")
    if not isinstance(projects, list) or not projects:
        raise SystemExit(f"{path}: no projects")
    return projects


def validate(projects: list[dict]) -> None:
    paths: dict[str, str] = {}
    for project in projects:
        for key in ("host", "owner", "repo", "path", "revision", "group", "url"):
            if not project.get(key):
                raise SystemExit(f"project missing {key}: {project!r}")
        path = project["path"]
        if path.startswith("/") or ".." in Path(path).parts:
            raise SystemExit(f"unsafe path: {path}")
        if path in paths:
            raise SystemExit(f"duplicate path {path}: {paths[path]} and {project['repo']}")
        paths[path] = project["repo"]
        if not project["url"].endswith(".git"):
            raise SystemExit(f"URL must end in .git: {project['url']}")
        if project["host"] not in ("codeberg", "gitlab", "github"):
            raise SystemExit(f"unsupported host: {project['host']}")


def render(projects: list[dict], selected: list[dict], title: str) -> str:
    remotes: dict[str, tuple[str, str]] = {}
    for project in selected:
        name = remote_name(project["host"], project["owner"])
        remotes[name] = (name, remote_fetch(project["host"], project["owner"]))

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f"<!-- Generated by scripts/build_manifest.py. {title}. -->",
        "<!-- Source inventory: projects.json; website: https://onyxpj.wikidot.com/ -->",
        "<manifest>",
    ]
    for name, fetch in sorted(remotes.values()):
        lines.append(
            f'  <remote name={quoteattr(name)} fetch={quoteattr(fetch)} '
            'review="https://github.com/XTOM0706/OnyxProject/pulls" />'
        )

    for project in sorted(selected, key=lambda p: p["path"]):
        name = remote_name(project["host"], project["owner"])
        lines.append(
            "  <project "
            f"name={quoteattr(project['repo'])} "
            f"path={quoteattr(project['path'])} "
            f"revision={quoteattr(project['revision'])} "
            f"remote={quoteattr(name)} "
            f"groups={quoteattr(project['group'])} />"
        )
    if title.startswith("OnyxUI"):
        lines.append('  <include name="ecosystem.xml" />')
    lines.append("</manifest>")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--projects", type=Path, default=DEFAULT_PROJECTS)
    parser.add_argument("--out", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--check", action="store_true", help="fail if the output differs")
    args = parser.parse_args()

    projects = load_projects(args.projects)
    validate(projects)

    system = [p for p in projects if p["group"] != "ecosystem"
              and not p["path"].startswith("upstream/")]
    ecosystem = [p for p in projects if p["group"] == "ecosystem"
                 or p["path"].startswith("upstream/")]

    default_xml = render(projects, system, "OnyxUI system and built-in apps")
    ecosystem_xml = render(projects, ecosystem, "Onyx ecosystem and upstream sources")

    if args.check:
        ok = True
        for path, expected in ((args.out, default_xml), (ECOSYSTEM_MANIFEST, ecosystem_xml)):
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                print(f"out of date: {path}", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    args.out.write_text(default_xml, encoding="utf-8")
    ECOSYSTEM_MANIFEST.write_text(ecosystem_xml, encoding="utf-8")
    print(f"wrote {args.out} ({len(system)} projects)")
    print(f"wrote {ECOSYSTEM_MANIFEST} ({len(ecosystem)} projects)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
